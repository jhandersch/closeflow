export const getDictionary = (language: AppLanguage): DictionaryNode => {
  return dictionaries[language] || dictionaries.de
}

export const translateKey = (dictionary: DictionaryNode, key: string, fallback?: string): string => {
  const parts = key.split(".")
  let current: DictionaryLeaf | DictionaryNode | undefined = dictionary

  for (const part of parts) {
    if (!current || typeof current === "string") {
      return fallback || key
    }

    current = current[part]
  }

  if (typeof current === "string") {
    return current
  }

  return fallback || key
}
